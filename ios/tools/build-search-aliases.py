#!/usr/bin/env python3
"""Build RailCore's search alias table (search-aliases.json).

One compact table the shared search engine indexes on top of each entity's
own names and readings:

- English station names from app/data/station-english-jp.json that the
  compact package's own romanized name (nameRoma) does not already carry.
  Operator-verified rows become `officialEnglish`, the rest `englishName`.
- A short curated list of alternate readings and former names, each with its
  source.

Usage: python3 -I ios/tools/build-search-aliases.py [--check]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "ios/RailKit/Sources/RailCore/Resources/search-aliases.json"

# kind: alternateReading | formerName | englishName | officialEnglish | reading
CURATED = [
    # 山手線 was read "Yamate-sen" until 1971; many riders and old maps still say Yamate.
    ("jp", "line", "jp-東日本旅客鉄道-山手線", "やまてせん", "alternateReading",
     "JR East: 山手線 reading standardized to やまのてせん in 1971"),
    ("jp", "line", "jp-東日本旅客鉄道-山手線", "Yamate Line", "alternateReading",
     "JR East: 山手線 reading standardized to やまのてせん in 1971"),
    ("jp", "line", "jp-神戸市-山手線", "やまてせん", "reading",
     "Kobe Municipal Subway: 山手線 (やまてせん)"),
    ("jp", "line", "jp-神戸市-山手線", "Yamate Line", "reading",
     "Kobe Municipal Subway: 山手線 (やまてせん)"),
    ("jp", "station", "007048", "梅田", "formerName", "Hankyu: 梅田 renamed 大阪梅田 on 2019-10-01"),
    ("jp", "station", "007071", "梅田", "formerName", "Hanshin: 梅田 renamed 大阪梅田 on 2019-10-01"),
    ("jp", "station", "007120", "三宮", "formerName", "Hankyu/Hanshin: 三宮 renamed 神戸三宮 (2013, 2014)"),
    ("jp", "station", "007308", "近鉄難波", "formerName", "Kintetsu: 近鉄難波 renamed 大阪難波 on 2009-03-20"),
    ("jp", "station", "003524", "業平橋", "formerName", "Tobu: 業平橋 renamed とうきょうスカイツリー on 2012-03-17"),
    ("jp", "station", "003521", "上野公園", "formerName", "Keisei: 上野公園 renamed 京成上野 in 1953"),
    ("jp", "station", "007321", "湊町", "formerName", "JR West: 湊町 renamed JR難波 on 1994-09-04"),
]


def package_romanized(region):
    package = json.loads((ROOT / f"app/public/rail/{region}-2025.json").read_text())
    names = {}
    for line in package["lines"]:
        for row in line["stations"]:
            if len(row) > 4 and row[4]:
                names.setdefault(row[0], set()).add(row[4])
    return names


def build():
    sources = []
    entries = []

    def source(text):
        if text not in sources:
            sources.append(text)
        return sources.index(text)

    english = json.loads((ROOT / "app/data/station-english-jp.json").read_text())["byCode"]
    romanized = package_romanized("jp")
    for code in sorted(english):
        row = english[code]
        name = (row.get("en") or "").strip()
        if not name or name in romanized.get(code, set()):
            continue
        kind = "officialEnglish" if row.get("status") == "official_verified" else "englishName"
        entries.append(["jp", "station", code, name, kind, source(row.get("source", "station-english-jp.json"))])
    for region, entity, key, alias, kind, why in CURATED:
        entries.append([region, entity, key, alias, kind, source(why)])
    return {
        "schema": "search-aliases/1",
        "note": "Generated by ios/tools/build-search-aliases.py. Rows: [region, entity (station|line), "
                "key (station source code | line id), alias, kind, source index].",
        "sources": sources,
        "entries": entries,
    }


def main():
    text = json.dumps(build(), ensure_ascii=False, separators=(",", ":")) + "\n"
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            print(f"{OUT} is stale", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text.encode())} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
